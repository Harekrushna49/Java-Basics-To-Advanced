//package Basic Programs;

public class Cal //Super Class/Parent Class
{
    public int Add(int a1, int b1)
    {
        return a1+b1;
    }
    public int Sub(int a1, int b1)
    {
        return b1-a1;
    }
    public int Mul(int a1, int b1)
    {
        return a1*b1;
    }
    public int Div(int a1, int b1)
    {
        return a1/b1;
    }
}